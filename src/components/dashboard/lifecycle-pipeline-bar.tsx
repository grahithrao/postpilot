"use client";

import * as React from "react";
import Link from "next/link";
import {
  FileText,
  Clock,
  CalendarClock,
  Send,
  AlertTriangle,
  ArrowRight,
  ShieldAlert,
  CheckCircle2,
} from "lucide-react";
import { cn } from "@/lib/utils";

interface PipelineStats {
  total: number;
  draft: number;
  pendingApproval: number;
  scheduled: number;
  published: number;
  failed: number;
}

export function LifecyclePipelineBar({ stats }: { stats: PipelineStats }) {
  const stages = [
    {
      id: "draft",
      stepNumber: "1",
      label: "Drafts",
      value: stats.draft,
      icon: FileText,
      href: "/content?status=DRAFT",
      statusDescription: "Content generated by AI or edited",
      badgeColor: "bg-slate-100 text-slate-700 dark:bg-slate-800 dark:text-slate-300",
      activeTone: "default",
    },
    {
      id: "pending",
      stepNumber: "2",
      label: "Pending Approval",
      value: stats.pendingApproval,
      icon: Clock,
      href: "/approvals",
      statusDescription: "Blocked: waiting for human review",
      badgeColor:
        stats.pendingApproval > 0
          ? "bg-amber-100 text-amber-800 border border-amber-300 dark:bg-amber-950/80 dark:text-amber-300"
          : "bg-sky-50 text-sky-700 dark:bg-sky-950 dark:text-sky-300",
      isBottleneck: stats.pendingApproval > 0,
      activeTone: stats.pendingApproval > 0 ? "warning" : "default",
    },
    {
      id: "scheduled",
      stepNumber: "3",
      label: "Scheduled",
      value: stats.scheduled,
      icon: CalendarClock,
      href: "/calendar",
      statusDescription: "Approved: locked into publishing slot",
      badgeColor: "bg-sky-100 text-sky-800 border border-sky-200 dark:bg-sky-900/60 dark:text-sky-300",
      activeTone: "sky",
    },
    {
      id: "published",
      stepNumber: "4",
      label: "Published",
      value: stats.published,
      icon: Send,
      href: "/content?status=PUBLISHED",
      statusDescription: "Successfully dispatched to platforms",
      badgeColor: "bg-emerald-100 text-emerald-800 border border-emerald-200 dark:bg-emerald-950 dark:text-emerald-300",
      activeTone: "success",
    },
  ];

  return (
    <div className="space-y-3">
      <div className="flex flex-wrap items-center justify-between gap-2 px-1">
        <div className="flex items-center gap-2">
          <h2 className="text-xs font-bold tracking-wider uppercase text-slate-500 dark:text-slate-400">
            Publishing Pipeline Status
          </h2>
          <span className="text-[11px] text-muted-foreground">({stats.total} total items managed)</span>
        </div>
        <div className="flex items-center gap-2 text-xs">
          <span className="flex size-2 rounded-full bg-sky-500" />
          <span className="text-slate-600 dark:text-slate-400 font-medium">Flow: Left to Right</span>
        </div>
      </div>

      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-4">
        {stages.map((stage, idx) => {
          const Icon = stage.icon;
          return (
            <Link
              key={stage.id}
              href={stage.href}
              className={cn(
                "group relative flex flex-col justify-between rounded-xl border p-4 transition-all duration-200",
                "bg-white dark:bg-slate-900 hover:shadow-md hover:shadow-sky-500/5",
                stage.isBottleneck
                  ? "border-amber-300/80 dark:border-amber-700 bg-amber-50/20 shadow-xs"
                  : "border-sky-100/90 dark:border-sky-950/70 hover:border-sky-300 dark:hover:border-sky-800",
              )}
            >
              <div>
                <div className="flex items-center justify-between gap-2">
                  <div className="flex items-center gap-2">
                    <span className="flex size-6 items-center justify-center rounded-md bg-sky-100/70 text-sky-800 dark:bg-sky-950 dark:text-sky-300 text-[11px] font-bold">
                      {stage.stepNumber}
                    </span>
                    <span className="text-xs font-semibold text-slate-700 dark:text-slate-300">{stage.label}</span>
                  </div>

                  <span className={cn("rounded-full px-2 py-0.5 text-xs font-bold tabular-nums", stage.badgeColor)}>
                    {stage.value}
                  </span>
                </div>

                <div className="mt-3 flex items-baseline gap-2">
                  <span className="text-3xl font-extrabold tracking-tight text-slate-900 dark:text-white tabular-nums">
                    {stage.value}
                  </span>
                  <span className="text-xs text-slate-500">posts</span>
                </div>

                <p className="mt-1.5 text-[11px] leading-relaxed text-slate-500 dark:text-slate-400">
                  {stage.statusDescription}
                </p>
              </div>

              <div className="mt-3 pt-2.5 border-t border-sky-50 dark:border-slate-800 flex items-center justify-between text-[11px] font-medium">
                <span className="text-sky-600 dark:text-sky-400 group-hover:underline">
                  {stage.id === "pending" && stage.value > 0 ? "Review now →" : "View posts →"}
                </span>
                {idx < 3 && (
                  <ArrowRight className="hidden lg:block text-slate-300 dark:text-slate-700 size-3" />
                )}
              </div>
            </Link>
          );
        })}
      </div>

      {stats.failed > 0 && (
        <div className="flex items-center justify-between gap-3 rounded-xl border border-red-200 bg-red-50/70 dark:bg-red-950/30 dark:border-red-900/50 px-4 py-2.5 text-xs">
          <div className="flex items-center gap-2 text-red-800 dark:text-red-300">
            <AlertTriangle className="size-4 shrink-0 text-red-600 dark:text-red-400" />
            <span>
              <strong>{stats.failed} post{stats.failed === 1 ? "" : "s"} failed during publishing.</strong> Check error logs and retry.
            </span>
          </div>
          <Link
            href="/content?status=FAILED"
            className="font-semibold text-red-700 dark:text-red-400 underline underline-offset-4 hover:text-red-800"
          >
            Review failed posts
          </Link>
        </div>
      )}
    </div>
  );
}
