import { FlaskConical, Sparkles } from "lucide-react";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import type { RuntimeFlags } from "@/lib/env";
import { cn } from "@/lib/utils";

/**
 * The Demo Mode indicator.
 *
 * Kept prominent on purpose: a reviewer should never be unsure whether a post
 * actually went to a real platform.
 */
export function DemoBadge({ flags, className }: { flags: RuntimeFlags; className?: string }) {
  if (!flags.demoMode && !flags.usingMockAi) return null;

  const both = flags.demoMode && flags.usingMockAi;
  const label = both ? "Demo Mode" : flags.demoMode ? "Simulated publishing" : "Mock AI";

  return (
    <Tooltip>
      <TooltipTrigger asChild>
        <span
          className={cn(
            "inline-flex items-center gap-1.5 rounded-md border border-amber-500/30 bg-amber-500/10 px-2 py-0.5 text-[11px] leading-5 font-medium text-amber-700 dark:text-amber-400",
            className,
          )}
        >
          <FlaskConical className="size-3" />
          {label}
        </span>
      </TooltipTrigger>
      <TooltipContent side="bottom" className="max-w-72">
        <p className="font-medium">Nothing leaves this machine.</p>
        <p className="mt-1 opacity-80">
          {flags.usingMockAi
            ? "Content is written by the built-in deterministic model, not an LLM API."
            : `Content is generated by ${flags.aiModel}.`}{" "}
          {flags.demoMode
            ? "Publishing is simulated by the platform adapters, so no post reaches a real social network."
            : "Publishing uses live platform credentials."}
        </p>
      </TooltipContent>
    </Tooltip>
  );
}

export function AiProviderBadge({ flags, className }: { flags: RuntimeFlags; className?: string }) {
  return (
    <span
      className={cn(
        "text-muted-foreground inline-flex items-center gap-1.5 text-[11px] font-medium",
        className,
      )}
    >
      <Sparkles className="size-3" />
      {flags.aiModel}
    </span>
  );
}
